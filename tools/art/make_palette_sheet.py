"""Writes the PaletteSheet preview scene (labelled swatches, rendered in-engine
with the theme fonts) into tools/preview/. palette.json comes from
make_theme.py palette."""
import os
import sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from palette import GROUPS  # noqa: E402
PREVIEW = os.path.join(os.path.dirname(HERE), "preview")
os.makedirs(PREVIEW, exist_ok=True)
rows = []
for t, items in GROUPS:
    rows.append(f'\t["#", "{t}", ""],')
    for k, v, n in items:
        rows.append(f'\t["{v}", "{k}", "{n}"],')
gd = '''extends Control
## Labelled palette swatches (generated by tools/art/make_palette_sheet.py).

const ROWS: Array = [
%s
]


func _ready() -> void:
	var flow: HFlowContainer = $Margin/Flow
	for r: Array in ROWS:
		if str(r[0]) == "#":
			var h := Label.new()
			h.text = str(r[1])
			h.theme_type_variation = &"HeaderSmall"
			h.custom_minimum_size = Vector2(696, 24)
			h.clip_text = true
			h.add_theme_font_size_override("font_size", 18)
			flow.add_child(h)
			continue
		var box := VBoxContainer.new()
		box.custom_minimum_size = Vector2(92, 0)
		box.add_theme_constant_override("separation", 0)
		var sw := Panel.new()
		var sb := StyleBoxFlat.new()
		sb.bg_color = Color(str(r[0]))
		sb.border_color = Color("#1A1311")
		sb.set_border_width_all(3)
		sb.set_corner_radius_all(6)
		sw.add_theme_stylebox_override("panel", sb)
		sw.custom_minimum_size = Vector2(92, 24)
		box.add_child(sw)
		for t: String in [str(r[1]), str(r[0])]:
			var l := Label.new()
			l.text = t
			l.theme_type_variation = &"Caption"
			l.add_theme_font_size_override("font_size", 10)
			l.add_theme_color_override("font_color", Color("#CFC6B8"))
			box.add_child(l)
		flow.add_child(box)
''' % "\n".join(rows)
with open(os.path.join(PREVIEW, "palette_sheet.gd"), "w") as f:
    f.write(gd)
tscn = '''[gd_scene load_steps=3 format=3]

[ext_resource type="Script" path="res://tools/preview/palette_sheet.gd" id="1_s"]
[ext_resource type="Theme" path="res://Assets/UI/Theme/jungle_theme.tres" id="2_t"]

[node name="PaletteSheet" type="ColorRect"]
layout_mode = 3
anchors_preset = 15
anchor_right = 1.0
anchor_bottom = 1.0
color = Color(0.1647, 0.1569, 0.149, 1)
theme = ExtResource("2_t")
script = ExtResource("1_s")

[node name="Margin" type="MarginContainer" parent="."]
layout_mode = 1
anchors_preset = 15
anchor_right = 1.0
anchor_bottom = 1.0
theme_override_constants/margin_left = 12
theme_override_constants/margin_top = 8
theme_override_constants/margin_right = 12

[node name="Flow" type="HFlowContainer" parent="Margin"]
layout_mode = 2
theme_override_constants/h_separation = 6
theme_override_constants/v_separation = 2
'''
with open(os.path.join(PREVIEW, "PaletteSheet.tscn"), "w") as f:
    f.write(tscn)
print("ok", len(rows))
