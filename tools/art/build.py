"""Writes every SVG of the Jungle Guild kit into Assets/UI/<group>/ and renders
the review sheets into tools/art/preview/ (git-ignored).
Usage: python3 tools/art/build.py [module ...]   (no args = all)

Sheets are rasterised by Godot's own SVG loader (render_sheets.gd) on a
throwaway project in a temp dir, never on this project. New SVGs need an
import stub (tools/art/write_import_stubs.sh Assets/UI) so they import as
DPITexture. Files in a group folder that no generator owns are listed, never
deleted."""
import importlib
import os
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from palette import PAL  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(HERE))      # the Godot project (res://)
OUT = os.path.join(ROOT, "Assets", "UI")
SHEETS = os.path.join(HERE, "preview")
GODOT = os.environ.get("GODOT", "/Applications/Godot.app/Contents/MacOS/Godot")
# module -> (folder, sheet sizes, columns)
GROUPS = {
    "icons_abilities": ("Icons/Abilities", "128,64,40", 3),
    "icons_stats": ("Icons/Stats", "64,40,24", 4),
    "icons_currency": ("Icons/Currency", "96,48,28", 3),
    "icons_roles": ("Icons/Roles", "64,40,28", 4),
    "icons_nav": ("Icons/Nav", "96,56,40", 3),
    "icons_ui": ("Icons/UI", "64,40,28", 4),
    "kit": ("Kit", "", 2),
    "crests": ("Crests", "256,96", 2),
    "lobby": ("Lobby", "360", 2),
}
KIT_SHEETS = [("kit_cards", "x2,x1", 5, "card_,padlock,dot_"), ("kit_nav", "x2,x1", 3, "plaque,arch"),
              ("kit_buttons", "x2,x1", 4, "btn_"), ("kit_panels", "x2,x1", 4, "panel,banner"),
              ("kit_slots", "x2,x1", 5, "slot_"), ("kit_ornaments", "x1", 4, "orn_,bg_")]


def render_sheet(proj, d, tag, sizes, cols, prefixes):
    sheet = os.path.join(SHEETS, "sheet_" + tag + ".png")
    cmd = [GODOT, "--headless", "--path", proj, "-s", os.path.join(HERE, "render_sheets.gd"), "--",
           d, sheet, sizes, str(cols), prefixes, PAL["bg_base"], PAL["card_fill"], PAL["bg_void"]]
    r = subprocess.run(cmd, capture_output=True, text=True)
    for line in (r.stdout + r.stderr).splitlines():
        if "ERROR" in line or "sheet_" in line or "error" in line.lower():
            print("  ", line)


def main():
    only = sys.argv[1:]
    os.makedirs(SHEETS, exist_ok=True)
    proj = tempfile.mkdtemp(prefix="art_sheets_")
    with open(os.path.join(proj, "project.godot"), "w") as f:
        f.write('config_version=5\n\n[application]\nconfig/name="art_sheets"\n'
                'config/use_custom_user_dir=true\nconfig/custom_user_dir_name="evolvemobile_art_sheets"\n\n'
                '[debug]\nfile_logging/enable_file_logging=false\nfile_logging/enable_file_logging.pc=false\n')
    try:
        for mod, (sub, sizes, cols) in GROUPS.items():
            if only and mod not in only:
                continue
            m = importlib.import_module(mod)
            d = os.path.join(OUT, sub)
            os.makedirs(d, exist_ok=True)
            for name, text in m.ICONS.items():
                with open(os.path.join(d, name + ".svg"), "w") as f:
                    f.write(text)
            print(mod, len(m.ICONS))
            stale = sorted(f for f in os.listdir(d) if f.endswith(".svg") and f[:-4] not in m.ICONS)
            if stale:
                print("   not generated by", mod + ":", ", ".join(stale))
            jobs = KIT_SHEETS if mod == "kit" else [(sub.replace("/", "_").lower(), sizes, cols, "")]
            for tag, sz, cl, pre in jobs:
                render_sheet(proj, d, tag, sz, cl, pre)
    finally:
        shutil.rmtree(proj, ignore_errors=True)
        if sys.platform == "darwin":   # the user dir Godot creates for the throwaway project
            shutil.rmtree(os.path.expanduser("~/Library/Application Support/evolvemobile_art_sheets"), ignore_errors=True)


if __name__ == "__main__":
    main()
